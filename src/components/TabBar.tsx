const TABS = [
  { href: "/", label: "Heute", Icon: TodayIcon },
  { href: "/verlauf", label: "Verlauf", Icon: HistoryIcon },
  { href: "/einstellungen", label: "Einstellungen", Icon: SettingsIcon },
];

export default function TabBar() {
  const pathname = usePathname();

  return (
    <nav className="sticky bottom-0 flex border-t border-border bg-card">
      {TABS.map(({ href, label, Icon }) => {
        const active = pathname === href;
        return (
          <Link
            key={href}
            href={href}
            className="flex flex-1 flex-col items-center gap-1 py-3 text-xs"
            style={{ color: active ? "var(--accent)" : "var(--accent-inactive)" }}
          >
            <Icon active={active} />
            {label}
          </Link>
        );
      })}
    </nav>
  );
}
